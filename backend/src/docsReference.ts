import { buildApp } from './app.ts';
import { loadConfig } from './config.ts';
import { openDb } from './db.ts';
import { ConsoleMailer } from './mailer.ts';

/** Generated references for `docs/` (#586): kept here so the docs test and `npm run docs` share them. */
export interface RouteRef {
  method: string;
  path: string;
}

/** Every route the API registers, sorted by path then method (HEAD routes Fastify adds for GET left out). */
export const collectRoutes = async (): Promise<RouteRef[]> => {
  const routes: RouteRef[] = [];
  const app = buildApp({
    config: loadConfig({ NODE_ENV: 'test' }),
    db: openDb(':memory:'),
    mailer: new ConsoleMailer(() => {}),
    apple: async () => {
      throw new Error('unused');
    },
    onRoute: (r) => {
      for (const m of [r.method].flat()) if (m !== 'HEAD') routes.push({ method: m, path: r.url });
    },
  });
  await app.ready();
  await app.close();
  const seen = new Set<string>();
  return routes
    .filter((r) => !seen.has(`${r.method} ${r.path}`) && seen.add(`${r.method} ${r.path}`))
    .sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
};

/** SQLite schema after every migration, as `CREATE` statements sorted by table. */
export const dumpSchema = (): string => {
  const db = openDb(':memory:');
  const rows = db
    .prepare("SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY tbl_name, type DESC, name")
    .all() as { sql: string }[];
  db.close();
  return `-- Generated by \`npm run docs\` (backend/scripts/docs-reference.ts). Do not edit.\n\n${rows.map((r) => `${r.sql};`).join('\n\n')}\n`;
};

/** One row of a `docs/api/endpoints.md` table: `| METHOD | \`path\` | auth | summary | errors |`. */
export interface EndpointDoc extends RouteRef {
  tag: string;
  auth: string;
  summary: string;
  errors: string;
}

export const parseEndpoints = (md: string): EndpointDoc[] => {
  const rows: EndpointDoc[] = [];
  let tag = '';
  for (const line of md.split('\n')) {
    const h = /^## (.+)$/.exec(line);
    if (h) tag = h[1]!.trim();
    // Cells split on pipes not escaped as `\|`.
    const cells = line.startsWith('| ') ? line.slice(1, -1).split(/(?<!\\)\|/).map((c) => c.trim().replace(/\\\|/g, '|')) : [];
    const path = /^`([^`]+)`$/.exec(cells[1] ?? '');
    if (cells.length === 5 && /^(GET|POST|PUT|PATCH|DELETE)$/.test(cells[0]!) && path)
      rows.push({ method: cells[0]!, path: path[1]!, tag, auth: cells[2]!, summary: cells[3]!, errors: cells[4]! });
  }
  return rows;
};

const SECURITY: Record<string, object[]> = {
  '–': [],
  Bearer: [{ bearer: [] }],
  'Bearer + re-auth': [{ bearer: [], reauth: [] }],
  'X-Watch-Key': [{ watchKey: [] }],
  'X-Garmin-Token': [{ garminToken: [] }],
  'Apple JWS': [],
};

/** OpenAPI 3.1 document built from `docs/api/endpoints.md` (paths, auth, summaries); bodies are described in prose. */
export const openApi = (docs: EndpointDoc[]): object => {
  const paths: Record<string, Record<string, object>> = {};
  for (const d of docs) {
    const path = d.path.replace(/:([A-Za-z]+)/g, '{$1}');
    const params = [...d.path.matchAll(/:([A-Za-z]+)/g)].map((p) => ({ name: p[1], in: 'path', required: true, schema: { type: 'string' } }));
    (paths[path] ??= {})[d.method.toLowerCase()] = {
      tags: [d.tag],
      summary: d.summary.replace(/`/g, ''),
      ...(d.errors ? { description: `Errors / limits: ${d.errors.replace(/`/g, '')}` } : {}),
      ...(params.length ? { parameters: params } : {}),
      security: SECURITY[d.auth] ?? [],
      responses: {
        default: { description: 'See summary. Errors: `{error, message}`', content: { 'application/json': { schema: { $ref: '#/components/schemas/Error' } } } },
      },
    };
  }
  return {
    openapi: '3.1.0',
    info: {
      title: 'MonkeyWorkout API',
      version: '1',
      description: 'Generated by `npm run docs` from docs/api/endpoints.md. Conventions: docs/api/README.md.',
    },
    servers: [
      { url: 'https://workout.monkeygrade.cloud', description: 'production' },
      { url: 'https://workout-staging.monkeygrade.cloud', description: 'staging' },
      { url: 'http://localhost:7443', description: 'DEV' },
    ],
    tags: [...new Set(docs.map((d) => d.tag))].map((name) => ({ name })),
    paths,
    components: {
      securitySchemes: {
        bearer: { type: 'http', scheme: 'bearer', bearerFormat: 'JWT', description: 'Access token (15 min) from /v1/auth/*' },
        reauth: { type: 'apiKey', in: 'header', name: 'X-Reauth-Token', description: '5-minute grant from POST /v1/me/reauth' },
        watchKey: { type: 'apiKey', in: 'header', name: 'X-Watch-Key', description: 'Apple Watch upload key from POST /v1/me/watch-key' },
        garminToken: { type: 'apiKey', in: 'header', name: 'X-Garmin-Token', description: 'Garmin watch token from POST /v1/garmin/pair' },
      },
      schemas: {
        Error: { type: 'object', required: ['error', 'message'], properties: { error: { type: 'string' }, message: { type: 'string' } } },
      },
    },
  };
};
